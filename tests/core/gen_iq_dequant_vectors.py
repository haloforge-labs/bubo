"""Generates ggml_iq_dequant_vectors.inc for ggml_iq_dequant_test.cpp.

The expected floats of IQ2_XXS, IQ2_XS, IQ2_S and IQ3_XXS come from the gguf-py reference dequantizer (pip install gguf); Q2_0 is not in
gguf-py, so its expected values follow ggml-org/llama.cpp bec4772f `dequantize_row_q2_0`: y = ((code - 1) * d) with code = (qs[j/4] >> 2*(j%4)) & 3.
Blocks are seeded random bytes with a fixed finite fp16 scale. Run: python gen_iq_dequant_vectors.py > ggml_iq_dequant_vectors.inc
"""
import struct
import sys

import numpy as np
from gguf import GGMLQuantizationType as T
from gguf.constants import GGML_QUANT_SIZES
from gguf.quants import dequantize

BLOCKS = 3


def make_blocks(rng, qtype_size, scale_choices):
    raw = rng.integers(0, 256, size=(BLOCKS, qtype_size), dtype=np.uint8)
    for b in range(BLOCKS):
        raw[b, 0:2] = np.frombuffer(np.float16(scale_choices[b]).tobytes(), dtype=np.uint8)
    return raw


def emit(name, raw, expected):
    print(f"constexpr std::size_t k{name}Blocks = {raw.shape[0]};")
    print(f"constexpr std::uint8_t k{name}Bytes[] = {{")
    flat = raw.reshape(-1)
    for i in range(0, len(flat), 24):
        print("    " + ", ".join(str(int(v)) for v in flat[i:i + 24]) + ",")
    print("};")
    exp = expected.astype(np.float32).reshape(-1)
    print(f"constexpr float k{name}Expected[] = {{")
    for i in range(0, len(exp), 6):
        print("    " + ", ".join(repr(float(np.format_float_positional(v, unique=True, trim='-'))) + "F" for v in exp[i:i + 6]) + ",")
    print("};")
    print()


def main():
    rng = np.random.default_rng(20261020)
    scales = [0.0123, -0.5, 1.75]
    print("// Generated by gen_iq_dequant_vectors.py (gguf-py reference; Q2_0 from llama.cpp bec4772f). Do not edit.")
    for name, qt in (("Iq2Xxs", T.IQ2_XXS), ("Iq2Xs", T.IQ2_XS), ("Iq2S", T.IQ2_S), ("Iq3Xxs", T.IQ3_XXS)):
        block, size = GGML_QUANT_SIZES[qt]
        raw = make_blocks(rng, size, scales)
        emit(name, raw, dequantize(raw, qt))
    raw = make_blocks(rng, 18, scales)
    exp = np.zeros((BLOCKS, 64), dtype=np.float32)
    for b in range(BLOCKS):
        d = np.float32(np.frombuffer(raw[b, 0:2].tobytes(), dtype=np.float16)[0])
        for j in range(64):
            code = (int(raw[b, 2 + j // 4]) >> (2 * (j % 4))) & 3
            exp[b, j] = np.float32(code - 1) * d
    emit("Q20", raw, exp)


if __name__ == "__main__":
    main()
