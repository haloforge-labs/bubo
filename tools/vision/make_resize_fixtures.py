"""Generates tests/core/image_resize_fixtures.hpp: Pillow BICUBIC resizes of small deterministic RGB images.
Usage: python tools/vision/make_resize_fixtures.py > tests/core/image_resize_fixtures.hpp   (needs Pillow; recorded version in the header)"""
import sys
import PIL
from PIL import Image

CASES = [  # (in_w, in_h, out_w, out_h, seed)
    (17, 13, 8, 6, 1),     # shrink, non-integer ratio
    (9, 7, 20, 15, 2),     # enlarge
    (40, 36, 48, 48, 3),   # enlarge a little (the Gemma 4 case: sides become multiples of 48)
    (100, 75, 24, 18, 4),  # shrink more than 4x: wide filter support
    (31, 5, 31, 12, 5),    # vertical pass only
    (22, 30, 11, 30, 6),   # horizontal pass only
    (32, 24, 48, 24, 7),   # horizontal enlarge only
    (50, 50, 50, 50, 8),   # same size: copy
    (3, 2, 24, 16, 9),     # tiny source, large output
]


def pixels(w, h, seed):
    state = (0x9E3779B9 * seed) & 0xFFFFFFFF or 1
    out = bytearray()
    for _ in range(w * h * 3):
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        out.append((state >> 8) & 0xFF)
    return bytes(out)


print("// Generated by tools/vision/make_resize_fixtures.py with Pillow %s: Image.resize(size, Image.BICUBIC)." % PIL.__version__)
print("// Input pixels come from the xorshift32 generator in image_resize_test.cpp (same seed, same sequence).")
print("#pragma once")
print("#include <array>")
print("#include <cstdint>")
print("#include <vector>")
print("namespace resize_fixtures {")
print("struct Case { std::uint32_t in_w, in_h, out_w, out_h, seed; std::vector<std::uint8_t> expected; };")
print("inline const std::vector<Case>& Cases() {")
print("  static const std::vector<Case> cases = {")
for in_w, in_h, out_w, out_h, seed in CASES:
    img = Image.frombytes("RGB", (in_w, in_h), pixels(in_w, in_h, seed))
    res = img.resize((out_w, out_h), Image.BICUBIC)
    data = res.tobytes()
    body = ",".join(str(b) for b in data)
    print("    {%d, %d, %d, %d, %d, {%s}}," % (in_w, in_h, out_w, out_h, seed, body))
print("  };")
print("  return cases;")
print("}")
print("}  // namespace resize_fixtures")
