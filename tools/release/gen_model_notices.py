"""Generate src/core/prepare/model_notices.inc from the approved notice files.

Usage: python -I tools/release/gen_model_notices.py NOTICE_DIR OUTPUT.inc
NOTICE_DIR must hold exactly LICENSE, NOTICE and PROVENANCE.md. The bytes are
embedded verbatim (hex escapes) and the SHA-256 is computed over those bytes.
"""
import hashlib
import pathlib
import sys

NAMES = ("LICENSE", "NOTICE", "PROVENANCE.md")
MAX_BYTES = 1 << 20


def literal(data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 20):
        lines.append('"' + "".join("\\x%02x" % b for b in data[i:i + 20]) + '"')
    return "\n".join(lines) if lines else '""'


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    folder = pathlib.Path(sys.argv[1])
    present = sorted(p.name for p in folder.iterdir())
    if present != sorted(NAMES):
        print("expected exactly", NAMES, "found", present)
        return 1
    out = ["// Generated by tools/release/gen_model_notices.py; exact approved bytes.",
           "const std::vector<ModelNotice> kModelNotices{"]
    for name in NAMES:
        data = (folder / name).read_bytes()
        if not data or len(data) > MAX_BYTES:
            print(name, "must be 1..1048576 bytes")
            return 1
        out.append('{"%s","%s",' % (name, hashlib.sha256(data).hexdigest()))
        out.append(literal(data) + "},")
    out.append("};")
    pathlib.Path(sys.argv[2]).write_bytes(("\n".join(out) + "\n").encode("ascii"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
