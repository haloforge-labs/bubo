"""Generate a model_notices*.inc from the approved notice files.

Usage: python -I tools/release/gen_model_notices.py [--check] NOTICE_DIR OUTPUT.inc [VARIABLE]
NOTICE_DIR must hold exactly LICENSE, NOTICE and PROVENANCE.md. The bytes are
embedded verbatim (hex escapes) and the SHA-256 is computed over those bytes.
VARIABLE names the generated vector (default kModelNotices).

Three sets are embedded (source files in tools/release/model-notices/):
  huihui   -> src/core/prepare/model_notices.inc           kModelNotices
  original -> src/core/prepare/model_notices_original.inc  kOriginalModelNotices
  lowmemory   -> src/core/prepare/model_notices_lowmemory.inc    kLowMemoryModelNotices

--check writes nothing. It exits 1 when OUTPUT.inc differs from the regenerated
text (line endings are compared as LF).
"""
import hashlib
import pathlib
import sys

NAMES = ("LICENSE", "NOTICE", "PROVENANCE.md")
MAX_BYTES = 1 << 20


def literal(data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 20):
        lines.append('"' + "".join("\\x%02x" % b for b in data[i:i + 20]) + '"')
    return "\n".join(lines) if lines else '""'


def main() -> int:
    args = sys.argv[1:]
    check = "--check" in args
    args = [a for a in args if a != "--check"]
    if len(args) not in (2, 3):
        print(__doc__)
        return 2
    variable = args[2] if len(args) == 3 else "kModelNotices"
    folder = pathlib.Path(args[0])
    present = sorted(p.name for p in folder.iterdir())
    if present != sorted(NAMES):
        print("expected exactly", NAMES, "found", present)
        return 1
    out = ["// Generated by tools/release/gen_model_notices.py; exact approved bytes.",
           "const std::vector<ModelNotice> %s{" % variable]
    for name in NAMES:
        data = (folder / name).read_bytes()
        if not data or len(data) > MAX_BYTES:
            print(name, "must be 1..1048576 bytes")
            return 1
        out.append('{"%s","%s",' % (name, hashlib.sha256(data).hexdigest()))
        out.append(literal(data) + "},")
    out.append("};")
    text = ("\n".join(out) + "\n").encode("ascii")
    target = pathlib.Path(args[1])
    if check:
        if not target.exists() or target.read_bytes().replace(b"\r\n", b"\n") != text:
            print("FAIL:", target, "differs from", folder)
            return 1
        print("PASS:", target, "equals", folder)
        return 0
    target.write_bytes(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
