#include <algorithm>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <sstream>

#include "src/core/prepare/hash_file.hpp"
#include "src/core/prepare/runtime_table.hpp"
#include "src/core/prepare/zip_reader.hpp"

int main(int argc, char** argv) {
  try {
    if (argc == 4 && std::string_view(argv[1]) == "--notices") {
      const auto root = std::filesystem::u8path(argv[2]);
      std::vector<std::filesystem::path> files;
      for (const auto& entry :
           std::filesystem::recursive_directory_iterator(root)) {
        if (entry.is_symlink())
          throw std::runtime_error("notice symlink refused");
        if (entry.is_regular_file())
          files.push_back(entry.path());
      }
      std::sort(files.begin(), files.end());
      std::ostringstream content;
      content << "// Exact release-thread text bytes; generated with linked "
                 "OpenSSL SHA-256.\n"
                 "const std::vector<RuntimeNotice> kRuntimeNotices{\n";
      for (const auto& file : files) {
        const auto name = file.lexically_relative(root).generic_string();
        if (!bubo::prepare::SafeZipPath(name) ||
            std::filesystem::file_size(file) > 1024 * 1024)
          throw std::runtime_error("invalid notice path/size");
        std::ifstream input(file, std::ios::binary);
        const std::string text((std::istreambuf_iterator<char>(input)), {});
        content << "{\"" << name << "\",\"" << bubo::prepare::HashFile(file)
                << "\",\n\"";
        unsigned column = 0;
        for (unsigned char byte : text) {
          content << "\\x" << std::hex << std::setw(2) << std::setfill('0')
                  << unsigned(byte);
          if (++column == 20) {
            content << "\"\n\"";
            column = 0;
          }
        }
        content << "\"},\n";
      }
      content << "};\n";
      std::ofstream output(std::filesystem::u8path(argv[3]), std::ios::binary);
      output << content.str();
      if (!output)
        throw std::runtime_error("notice output failed");
      std::cout << "PASS: embedded " << files.size()
                << " exact release-thread notice files\n";
      return 0;
    }
    const bool fixture = argc == 7 && std::string_view(argv[1]) == "--fixture";
    if ((!fixture && argc != 6) || (fixture && argc != 7)) {
      std::cerr << "Usage: prepare_runtime_table [--fixture] CORE.whl "
                   "LIBRARIES.whl DEVICE.whl TABLE.tsv EMBEDDED.inc\n";
      return 2;
    }
    const int start = fixture ? 2 : 1;
    const auto rows = bubo::prepare::GenerateRuntimeTable(
        {std::filesystem::u8path(argv[start]),
         std::filesystem::u8path(argv[start + 1]),
         std::filesystem::u8path(argv[start + 2])},
        !fixture);
    const auto text = bubo::prepare::SerializeRuntimeTable(rows);
    std::ofstream table(std::filesystem::u8path(argv[start + 3]),
                        std::ios::binary);
    std::ofstream embedded(std::filesystem::u8path(argv[start + 4]),
                           std::ios::binary);
    table << text;
    embedded << "// Generated by prepare_runtime_table; pinned wheels verified "
                "against Appendix B.\n"
             << "inline constexpr std::string_view kRuntimeMembers = "
                "R\"BUBO_RUNTIME("
             << text << ")BUBO_RUNTIME\";\n";
    if (!table || !embedded)
      throw std::runtime_error("cannot write generated table");
    std::uint64_t total = 0;
    for (const auto& r : rows)
      total += r.size;
    std::cout << "PASS: "
              << (fixture ? "synthetic fixture"
                          : "Appendix B archives and Appendix A DLL pins")
              << "; rows=" << rows.size() << "; extraction_bytes=" << total
              << '\n';
  } catch (const std::exception& e) {
    std::cerr << e.what() << '\n';
    return 1;
  }
}
