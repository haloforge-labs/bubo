// One generated inventory feeds docs and the package. No network is used here.
import * as checker from 'license-checker-rseidelsohn';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { parseArgs } from 'node:util';

const { values: args } = parseArgs({ options: Object.fromEntries(['frontend','out','report','go-tool','go-data','provenance'].map(k => [k,{type:'string'}])) });
for (const key of ['frontend','out','report','go-tool','go-data','provenance']) if (!args[key]) throw Error(`Missing --${key}`);
const readJSON = name => JSON.parse(fs.readFileSync(name,'utf8').replace(/^\uFEFF/,''));
const lock = readJSON(path.join(args.frontend,'package-lock.json'));
const hash = text => crypto.createHash('sha256').update(text).digest('hex');
const rows = [];
fs.mkdirSync(args.out,{recursive:true});
function add(name,version,license,source,binary,files) {
  const texts = files.map(file => fs.readFileSync(file));
  if (!texts.length) throw Error(`Missing license text: ${name}`);
  const text = Buffer.concat(texts.flatMap((t,i) => [Buffer.from(`Licence text ${i+1}\n\n`),t,Buffer.from('\n')]));
  const filename = `notice-${hash(name+'@'+version).slice(0,16)}.txt`;
  fs.writeFileSync(path.join(args.out,filename),text);
  rows.push({name,version,license,source,binary,notice:filename});
}
// Arborist treats junction-backed dependencies as extraneous. Scan all installed
// texts, then select the lock's production records, checking completeness below.
const scanned = await new Promise((resolve,reject) => checker.init({start:args.frontend,production:false,excludePrivatePackages:true}, (err,result) => err ? reject(err) : resolve(result)));
const production = Object.entries(lock.packages).filter(([name,data]) => name && !data.dev);
const npm = Object.fromEntries(Object.entries(scanned).filter(([id]) => {
  const at=id.lastIndexOf('@'), name=id.slice(0,at), version=id.slice(at+1);
  return production.some(([key,data]) => key.endsWith(`node_modules/${name}`) && data.version===version);
}));
for (const [key,data] of production) {
  if (data.optional && ((data.os && !data.os.includes(process.platform)) || (data.cpu && !data.cpu.includes(process.arch)))) continue;
  const name=key.slice(key.lastIndexOf('node_modules/')+'node_modules/'.length);
  if (!npm[`${name}@${data.version}`]) throw Error(`Missing production lock notice: ${name}@${data.version}`);
}
for (const [id,meta] of Object.entries(npm)) {
  const at = id.lastIndexOf('@'), name = id.slice(0,at), version = id.slice(at+1);
  const record = Object.entries(lock.packages).find(([key,value]) => key.endsWith(`node_modules/${name}`) && value.version === version && !value.dev);
  if (!record) throw Error(`Inventory differs from production lock: ${id}`);
  const files = [meta.licenseFile,meta.noticeFile].flat().filter(Boolean);
  add(name,version,[meta.licenses].flat().join(' OR '),meta.repository || `https://www.npmjs.com/package/${name}/v/${version}`,'GUI',files);
}
const mpl = Object.entries(lock.packages).filter(([name]) => /(^|\/)lightningcss(?:\/|$|-)/.test(name));
if (!mpl.length || mpl.some(([,data]) => !data.dev) || Object.keys(npm).some(name => name.startsWith('lightningcss'))) throw Error('lightningcss must be exclusively build-only');
const goData = readJSON(args['go-data']);
for (const [binary,data] of Object.entries(goData)) {
  for (const r of data) {
    // pkg.go.dev derives source links from the pinned registry module, offline.
    add(r.Name,r.Version,r.License,`https://pkg.go.dev/${r.Name}@${r.Version}`,binary,[r.LicensePath]);
  }
}
const classify = file => execFileSync(args['go-tool'],['-license',file],{encoding:'utf8'}).trim();
const vendored = readJSON(new URL('./vendored.json',import.meta.url));
for (const r of vendored) {
  const file = path.join(args.frontend,r.file);
  add(r.name,r.version || `licence-sha256:${hash(fs.readFileSync(file)).slice(0,16)}`,classify(file),r.source,'GUI',[file]);
}
const goroot = execFileSync('go',['env','GOROOT'],{encoding:'utf8'}).trim();
const goLicense = path.join(goroot,'LICENSE');
add('Go standard library',execFileSync('go',['version'],{encoding:'utf8'}).trim().split(' ')[2],classify(goLicense),'https://go.dev/LICENSE','GUI, helper',[goLicense]);
rows.sort((a,b) => a.name.localeCompare(b.name) || a.binary.localeCompare(b.binary));
const counts = new Map();
for (const r of rows) counts.set(r.license,(counts.get(r.license)||0)+1);
const flagged = rows.filter(r => !/^(MIT|BSD-2-Clause|BSD-3-Clause|Apache-2.0|ISC)$/.test(r.license));
const cell = value => String(value).replaceAll('|','\\|').replaceAll('\n',' ');
const report = [
  '# Generated GUI and updater third-party inventory','',
  `Generated by license-checker-rseidelsohn 5.0.1 and google/go-licenses v1.6.0 (offline adapter). Frontend: ${args.provenance}.`,
  `Production package-lock.json SHA-256: ${hash(fs.readFileSync(path.join(args.frontend,'package-lock.json')))}.`,
  'Go libraries are discovered for the Windows production,wv2runtime.error build with CGO_ENABLED=0; local Bubo modules are first-party.',
  'This inventory covers the production React frontend and Windows GUI/helper dependencies. It is not a release approval.', '',
  '| Component | Version | Licence | Source URL | Binary | Package text |',
  '| --- | --- | --- | --- | --- | --- |',
  ...rows.map(r => `| ${[r.name,r.version,r.license,r.source,r.binary,`licenses/gui/${r.notice}`].map(cell).join(' | ')} |`),
  '', '## Counts by licence','',...Array.from(counts).sort().map(([license,count]) => `- ${license}: ${count}`),
  '',`Total: ${rows.length} component/binary records; npm production: ${Object.keys(npm).length}; Go records: ${Object.values(goData).reduce((n,d) => n+d.length,0)}; vendored/fonts: ${vendored.length}; Go standard library: 1.`,
  '', '## REVIEW-NOTES','',
  ...flagged.map(r => `- FLAG: ${r.name}@${r.version}: ${r.license}; ${r.binary}.`),
  ...(flagged.length ? [] : ['- No shipped dependency is identified as MPL, LGPL, GPL or unknown.']),
  `- lightningcss: ${mpl.length} locked entries, all dev-only; absent from the production dependency graph. Its native build tool is not shipped.`,
  '- go-licenses report/save source-URL discovery requires network beyond the allowed registries. The offline adapter uses the same Libraries API and classifier, local module-cache texts, and pkg.go.dev source references.',
  '- go-licenses warns that golang.org/x/image/vector has assembly. This is part of the same BSD module; no separate external object/library is included.',
  '- Vendored versions without upstream version files use a licence-text hash; the pinned frontend revision identifies the actual font assets.',
  '', 'Regenerate with tools/release/gui-licenses/generate.ps1. Licence texts are generated into the supplied bundle directory, outside Git.', ''
].join('\n');
fs.mkdirSync(path.dirname(args.report),{recursive:true});
fs.writeFileSync(args.report,report);
fs.writeFileSync(path.join(args.out,'THIRD-PARTY-GUI.md'),report);
fs.writeFileSync(path.join(args.out,'inventory.json'),JSON.stringify(rows,null,2)+'\n');
console.log(`PASS: inventory records=${rows.length}; npm=${Object.keys(npm).length}; review-flags=${flagged.length}`);
for (const [license,count] of Array.from(counts).sort()) console.log(`${license}: ${count}`);
