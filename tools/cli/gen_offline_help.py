"""Write src/cli/offline_help.inc: the help text of every engine command.

bubo.exe prints this text when the engine cannot load (no AMD runtime yet).
Run it with a bubo.exe that has its runtime, after any change to a help text:

    python tools/cli/gen_offline_help.py PATH-TO-bubo.exe

argparse_golden_test.py (group "offline") fails when the table and the engine
disagree.
"""

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tests" / "cli" / "contract"))
from argparse_golden_test import HELP_TOPICS  # noqa: E402

BACKSLASH = chr(92)


def literal(line):
    """One C string literal for one help line, ASCII only, ending in a newline."""
    out = []
    for byte in line.encode("utf-8"):
        if byte in (0x22, 0x5C):
            out.append(BACKSLASH + chr(byte))
        elif 0x20 <= byte < 0x7F:
            out.append(chr(byte))
        else:
            out.append(BACKSLASH + "%03o" % byte)
    return '"' + "".join(out) + BACKSLASH + 'n"'


def main():
    exe = Path(sys.argv[1]).resolve()
    rows = []
    for topic in HELP_TOPICS:
        run = subprocess.run([str(exe), *topic, "--help"], capture_output=True, timeout=60,
                             creationflags=subprocess.CREATE_NO_WINDOW)
        text = run.stdout.decode("utf-8").replace("\r\n", "\n")
        if run.returncode != 0 or not text:
            raise SystemExit(f"{' '.join(topic)} --help: exit {run.returncode}, {run.stderr.decode()[:200]}")
        lines = "\n".join("      " + literal(line) for line in text.rstrip("\n").split("\n"))
        rows.append('    {"' + " ".join(topic) + '",\n' + lines + "},")
    header = ("// Generated by tools/cli/gen_offline_help.py. Do not edit.\n"
              "// key = the command words, text = the help the engine prints.\n")
    target = Path(__file__).resolve().parents[2] / "src" / "cli" / "offline_help.inc"
    text = header + "\n".join(rows) + "\n"
    if not target.exists() or target.read_text(encoding="utf-8") != text:
        target.write_text(text, encoding="utf-8", newline="\r\n")
    print(f"{len(rows)} help texts -> {target}")


if __name__ == "__main__":
    main()
