import { readFile, writeFile } from 'node:fs/promises'

// Read the CLI's compatibility rules without running an executable or server.
const source = await readFile(
  new URL('../../../../src/cli/serve/release_profile.cpp', import.meta.url),
  'utf8',
)
const aliases = Object.fromEntries(
  [
    ...source.matchAll(
      /if \(inputs\.profile == "([^"]+)"\)\s*inputs\.profile = "([^"]+)";/g,
    ),
  ].map((match) => [match[1], match[2]]),
)
if (!Object.keys(aliases).length)
  throw new Error(
    'No CLI profile compatibility rules found; review the CLI parser before regenerating.',
  )
await writeFile(
  new URL('../src/generated/profile-aliases.ts', import.meta.url),
  `// Generated by scripts/generate-profile-aliases.mjs from the CLI profile parser.\nexport const profileAliases: Readonly<Record<string, string>> = ${JSON.stringify(aliases, null, 2)}\n`,
)
